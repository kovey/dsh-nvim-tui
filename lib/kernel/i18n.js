/**
 * Runner-side i18n: user-facing strings are zh literals in code; `t()` looks
 * them up in the en dictionary. Unknown keys fall back to the zh literal, so
 * partial coverage degrades gracefully. The Lua UI (key hints, float
 * footers) remains Chinese for now — documented limitation.
 *
 * Locale selection: `config.locale` / `DSH_NVIM_TUI_LOCALE` (default `zh`),
 * switchable at runtime via `/locale zh|en`.
 *
 * @module dsh-nvim-tui/i18n
 */
let current = 'zh';
export function setLocale(locale) {
    current = locale;
}
export function locale() {
    return current;
}
/** Reverse index (en → zh) filled while translating. Command descriptions
 *  are translated ONCE at registration; without this, switching back to zh
 *  could not restore the original literal (the en string has no zh key). */
const REVERSE = new Map();
/** Translate a template with `{name}` placeholders. A template literal passed
 *  to `t()` can NEVER match the dictionary (the dictionary holds the
 *  pre-interpolation text, the call site passes the interpolated string), so
 *  every templated string must go through this instead. */
export function tf(zh, vars) {
    const lookup = (key) => Array.isArray(vars)
        ? vars[Number(key)]
        : vars[key];
    return t(zh).replace(/\{(\w+)\}/g, (whole, key) => {
        const v = lookup(key);
        return v === undefined ? whole : String(v);
    });
}
/** Translate one zh literal; unknown keys return the literal unchanged. */
export function t(zh) {
    if (current !== 'en')
        return REVERSE.get(zh) ?? zh;
    const en = EN_DICT[zh];
    if (en === undefined)
        return zh;
    REVERSE.set(en, zh);
    return en;
}
